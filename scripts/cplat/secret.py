"""`instance secret`: set / list the values of `remote` secrets in the local cluster's secret store (ADR-018).

`generate` secrets need nothing: External Secrets Operator creates the values in the cluster. `remote` secrets are read
from the `platform-secrets` store, which locally is the `secrets-store` namespace; values are written there with this
command (from a hidden prompt or stdin) and never touch git. Real clusters use their own store (Vault, AWS, ...).
"""
from __future__ import annotations

import argparse
import getpass
import json
import sys
from pathlib import Path

import gitops
import model
from core import PlatformError, Report

STORE_NS = "secrets-store"


def kubectl(args: list[str], input_text: str | None = None) -> str:
    """`kubectl` wrapper (tests replace this)."""
    import subprocess
    proc = subprocess.run(["kubectl", *args], input=input_text, text=True, capture_output=True)
    if proc.returncode != 0:
        raise PlatformError(f"kubectl {' '.join(args[:4])} failed: {(proc.stderr or proc.stdout).strip().splitlines()[-1:]}")
    return proc.stdout


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="cplat instance secret", description=__doc__)
    sub = p.add_subparsers(dest="action", required=True)
    s = sub.add_parser("set", help="write one value into the local secret store")
    s.add_argument("instance", help="<component>/<env>, e.g. todo-api/dev")
    s.add_argument("secret", help="secret name as declared in system.yaml")
    s.add_argument("key")
    s.add_argument("--value-stdin", action="store_true", help="read the value from stdin instead of prompting")
    l = sub.add_parser("list", help="show declared secrets and whether remote values are present")
    l.add_argument("--env", default="dev")
    for sp in (s, l):
        sp.add_argument("--system")
        sp.add_argument("--repo-dir", default=".")
        sp.add_argument("--context", help="kube context (default k3d-<system>-local)")
    return p


def main(argv: list[str]) -> int:
    ns = build_parser().parse_args(argv)
    repo = Path(ns.repo_dir).resolve()
    app_dir = gitops.find_app(repo, ns.system)
    system = app_dir.name
    ctx = ["--context", ns.context or f"k3d-{system}-local"]
    m = model.load_dir(app_dir)

    if ns.action == "list":
        r = Report(title=f"secrets of {system} ({ns.env})")
        found = False
        for inst in m.instances_in(ns.env):
            for sec in m.secrets(inst.component, ns.env):
                found = True
                if sec.kind == "generate":
                    r.did.append(f"{inst.component}/{sec.name}: generated by External Secrets Operator ({', '.join(sec.keys)})")
                    continue
                try:
                    have = set(json.loads(kubectl([*ctx, "-n", STORE_NS, "get", "secret", sec.store_key, "-o", "json"])).get("data") or {})
                except PlatformError:
                    have = set()
                for k in sec.keys:
                    state = "set" if k in have else f"MISSING → cplat instance secret set {inst.component}/{ns.env} {sec.name} {k}"
                    r.did.append(f"{inst.component}/{sec.name}.{k}: {state}")
        if not found:
            r.did.append("no `secrets:` declared (add with `cplat component set <component> --generate NAME=KEY` or --secret)")
        r.emit(False, False)
        return 0

    component, _, env = ns.instance.partition("/")
    if not component or not env:
        raise PlatformError(f"'{ns.instance}' is not <component>/<env>", hint="e.g. todo-api/dev")
    if m.component(component) is None:
        raise PlatformError(f"no component '{component}'", hint="components: " + (", ".join(c.name for c in m.components) or "none"))
    secrets = m.secrets(component, env)
    sec = next((x for x in secrets if x.name == ns.secret and x.kind != "generate"), None)
    if sec is None:
        remote = [x.name for x in secrets if x.kind != "generate"]
        raise PlatformError(f"{component} has no remote secret '{ns.secret}' (remote secrets: {', '.join(remote) or 'none'})")
    if ns.key not in sec.keys:
        raise PlatformError(f"'{ns.key}' is not a key of '{ns.secret}'", hint="keys: " + ", ".join(sec.keys))
    value = sys.stdin.read().rstrip("\n") if ns.value_stdin else getpass.getpass(f"{ns.key} for {component} ({env}): ")
    if not value:
        raise PlatformError("empty value")
    name = sec.store_key
    if not _exists(ctx, name):
        kubectl([*ctx, "-n", STORE_NS, "create", "secret", "generic", name])
    kubectl([*ctx, "-n", STORE_NS, "patch", "secret", name, "--type", "merge", "--patch-file", "/dev/stdin"], json.dumps({"stringData": {ns.key: value}}))
    r = Report(title=f"secret {component}/{ns.secret}.{ns.key} ({env})")
    r.did.append(f"stored in {STORE_NS}/{name} (the value is not printed and not in git)")
    r.next_steps.append("ESO syncs it within the refresh interval (default 1h); force it: kubectl annotate externalsecret " + f"{ns.secret} -n {system}-{env} force-sync=$(date +%s) --overwrite")
    r.emit(False, False)
    return 0


def _exists(ctx: list[str], name: str) -> bool:
    try:
        kubectl([*ctx, "-n", STORE_NS, "get", "secret", name])
        return True
    except PlatformError:
        return False
