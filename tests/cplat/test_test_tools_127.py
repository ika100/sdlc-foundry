"""Spec 127 acceptance tests, the pinned test tools: AC-127.4 (requirements-test.in/.txt), AC-127.5 (the three suite commands install only
from requirements-test.txt; scripts/check-pins.py part 4 fails otherwise), AC-127.6 (the Dependabot pip entry).

File-content checks of the repository, plus runs of scripts/check-pins.py on a scratch checkout that violates part 4 (design.md,
"Test-tool pins"). The scratch checkout symlinks everything the script reads except the three suite files and requirements-test.txt."""
import re
import shutil
import subprocess
import sys

import pytest
import yaml

from system_fixtures import ROOT

PACKAGES = ["pytest", "pytest-xdist", "pyyaml", "ruamel.yaml"]
SUITE_FILES = [".github/workflows/ci.yml", "scripts/ci-local.sh", "devbox.json"]
REQ = "requirements-test.txt"
OLD_TOOLS = "--with pytest --with pytest-xdist --with pyyaml --with ruamel.yaml"
NEW_TOOLS = f"--with-requirements {REQ}"
PIN = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==([^\s;]+)(\s*;\s*.+)?$")


def norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def requirement_lines(path) -> list[str]:
    return [ln.strip() for ln in path.read_text().splitlines() if ln.strip() and not ln.lstrip().startswith(("#", "-"))
            and not ln.startswith((" ", "\t"))]


# ---------------- AC-127.4 ----------------

def test_requirements_test_in_lists_the_four_top_level_packages_unpinned_ac_127_4():  # AC-127.4
    p = ROOT / "requirements-test.in"
    assert p.is_file(), "requirements-test.in is missing"
    lines = [ln.strip() for ln in p.read_text().splitlines() if ln.strip() and not ln.strip().startswith("#")]
    assert sorted(lines) == sorted(PACKAGES), lines


def test_requirements_test_txt_is_uv_compiled_from_the_in_file_ac_127_4():  # AC-127.4
    p = ROOT / REQ
    assert p.is_file(), f"{REQ} is missing"
    head = p.read_text()
    assert "# This file was autogenerated by uv via the following command:" in head
    assert "uv pip compile --universal requirements-test.in -o requirements-test.txt" in head


def test_every_requirement_is_pinned_to_an_exact_version_ac_127_4():  # AC-127.4
    p = ROOT / REQ
    assert p.is_file(), f"{REQ} is missing"
    lines = requirement_lines(p)
    assert lines, "no requirements"
    bad = [ln for ln in lines if not PIN.match(ln)]
    assert bad == [], bad


def test_the_pins_cover_the_four_packages_and_their_dependencies_ac_127_4():  # AC-127.4
    p = ROOT / REQ
    assert p.is_file(), f"{REQ} is missing"
    names = {norm(PIN.match(ln).group(1)) for ln in requirement_lines(p) if PIN.match(ln)}
    top = {norm(x) for x in PACKAGES}
    assert top <= names, top - names
    assert {"execnet", "pluggy", "iniconfig", "packaging"} <= names, names  # pytest's and xdist's dependencies
    assert len(names) > len(top), "only the top-level packages are listed, not their dependencies"


# ---------------- AC-127.5: the suite commands ----------------

def suite_lines(rel: str) -> list[str]:
    return [ln for ln in (ROOT / rel).read_text().splitlines() if "pytest tests/cplat" in ln]


@pytest.mark.parametrize("rel", SUITE_FILES)
def test_the_suite_command_installs_only_from_requirements_test_txt_ac_127_5(rel):  # AC-127.5
    lines = suite_lines(rel)
    assert len(lines) == 1, (rel, lines)
    line = lines[0]
    assert f"uv run {NEW_TOOLS} pytest tests/cplat" in line, line
    for p in PACKAGES:
        assert not re.search(rf"--with[= ]\s*{re.escape(p)}(\s|$|[\"'])", line), (rel, p)


def test_the_ci_step_keeps_its_shard_flags_ac_127_5():  # AC-127.5
    line = suite_lines(".github/workflows/ci.yml")[0]
    assert "-n auto --shard ${{ matrix.shard }}/4 --shard-report shard-${{ matrix.shard }}.json" in line


# scratch checkout for check-pins.py ---------------------------------------

GOOD_REQ = "# This file was autogenerated by uv via the following command:\n#    uv pip compile --universal requirements-test.in -o requirements-test.txt\npytest==9.2.0\n"


def scratch(tmp_path, ci=None, ci_local=None, devbox=None, req=GOOD_REQ):
    """A copy of the repo layout where scripts/check-pins.py, the three suite files and requirements-test.txt are real files."""
    root = tmp_path / "repo"
    (root / "scripts").mkdir(parents=True)
    (root / ".github" / "workflows").mkdir(parents=True)
    for entry in ROOT.iterdir():
        if entry.name in {"scripts", ".github", "devbox.json", ".git", REQ, "node_modules", "site"}:
            continue
        (root / entry.name).symlink_to(entry)
    for entry in (ROOT / "scripts").iterdir():
        if entry.name not in {"check-pins.py", "ci-local.sh"}:
            (root / "scripts" / entry.name).symlink_to(entry)
    for entry in (ROOT / ".github").iterdir():
        if entry.name != "workflows":
            (root / ".github" / entry.name).symlink_to(entry)
    for entry in (ROOT / ".github" / "workflows").iterdir():
        if entry.name != "ci.yml":
            (root / ".github" / "workflows" / entry.name).symlink_to(entry)
    shutil.copy(ROOT / "scripts" / "check-pins.py", root / "scripts" / "check-pins.py")

    def good(rel):
        return (ROOT / rel).read_text().replace(OLD_TOOLS, NEW_TOOLS)

    (root / ".github/workflows/ci.yml").write_text(ci if ci is not None else good(".github/workflows/ci.yml"))
    (root / "scripts/ci-local.sh").write_text(ci_local if ci_local is not None else good("scripts/ci-local.sh"))
    (root / "devbox.json").write_text(devbox if devbox is not None else good("devbox.json"))
    if req is not None:
        (root / REQ).write_text(req)
    return root


def check(root):
    return subprocess.run([sys.executable, str(root / "scripts" / "check-pins.py")], cwd=root, capture_output=True, text=True, timeout=600)


def test_check_pins_passes_on_a_checkout_whose_suite_commands_install_from_the_file_ac_127_5(tmp_path):  # AC-127.5
    p = check(scratch(tmp_path))
    assert p.returncode == 0, p.stdout + p.stderr
    assert (ROOT / REQ).is_file() and suite_lines("devbox.json"), "control only: the repo itself is checked by the tests above"


def test_check_pins_fails_on_a_suite_command_without_the_requirements_file_ac_127_5(tmp_path):  # AC-127.5
    old_ci = (ROOT / ".github/workflows/ci.yml").read_text().replace(NEW_TOOLS, "--with pytest-xdist")  # spec 127 build: the repo has the new form
    assert NEW_TOOLS not in old_ci
    p = check(scratch(tmp_path, ci=old_ci))
    assert p.returncode == 1, p.stdout + p.stderr
    assert re.search(r"ERROR: \.github/workflows/ci\.yml:\d+: .*installs the test tools without requirements-test\.txt", p.stdout), p.stdout


@pytest.mark.parametrize("pkg", PACKAGES)
@pytest.mark.parametrize("form", ["--with {p}", "--with={p}", "--with {p}==1.0", "--with '{p}>=1'"])  # spec 127 review: a version spec too
def test_check_pins_fails_on_a_with_flag_for_any_of_the_four_packages_ac_127_5(tmp_path, pkg, form):  # AC-127.5
    devbox = (ROOT / "devbox.json").read_text().replace(NEW_TOOLS, f"{NEW_TOOLS} {form.format(p=pkg)}")  # spec 127 build: the repo has the new form
    assert form.format(p=pkg) in devbox
    p = check(scratch(tmp_path, devbox=devbox))
    assert p.returncode == 1, p.stdout + p.stderr
    assert f"devbox.json:" in p.stdout and f"installs {pkg} without requirements-test.txt" in p.stdout, p.stdout


def test_check_pins_fails_when_ci_local_has_no_suite_command_ac_127_5(tmp_path):  # AC-127.5
    text = "\n".join(ln for ln in (ROOT / "scripts/ci-local.sh").read_text().splitlines() if "pytest tests/cplat" not in ln)
    p = check(scratch(tmp_path, ci_local=text))
    assert p.returncode == 1, p.stdout + p.stderr
    assert "ERROR: scripts/ci-local.sh:0: pytest tests/cplat: the cplat suite command is missing" in p.stdout, p.stdout


def test_check_pins_fails_on_an_unpinned_requirement_line_ac_127_5(tmp_path):  # AC-127.5
    p = check(scratch(tmp_path, req=GOOD_REQ + "pluggy>=1.0\n"))
    assert p.returncode == 1, p.stdout + p.stderr
    assert re.search(r"ERROR: requirements-test\.txt:\d+: pluggy>=1\.0: not pinned to an exact version", p.stdout), p.stdout


# ---------------- AC-127.6 ----------------

def test_dependabot_updates_requirements_test_txt_monthly_in_one_group_ac_127_6():  # AC-127.6
    cfg = yaml.safe_load((ROOT / ".github" / "dependabot.yml").read_text())
    pips = [u for u in cfg["updates"] if u["package-ecosystem"] == "pip"]
    assert len(pips) == 1, "one pip entry expected"
    e = pips[0]
    assert e["directory"] == "/" or e.get("directories") == ["/"], e
    assert e["schedule"] == {"interval": "monthly"}, e
    groups = e["groups"]
    assert len(groups) == 1, groups
    assert next(iter(groups.values()))["patterns"] == ["*"], groups
